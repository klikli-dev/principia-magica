package com.klikli_dev.principiamagica.registry;

import com.klikli_dev.principiamagica.PrincipiaMagica;
import com.klikli_dev.principiamagica.content.golem.spec.GolemSpec;
import net.minecraft.network.syncher.EntityDataSerializer;
import net.neoforged.neoforge.registries.DeferredHolder;
import net.neoforged.neoforge.registries.DeferredRegister;
import net.neoforged.neoforge.registries.NeoForgeRegistries;

public class EntityDataSerializerRegistry {
    public static final DeferredRegister<EntityDataSerializer<?>> ENTITY_DATA_SERIALIZERS = DeferredRegister.create(NeoForgeRegistries.ENTITY_DATA_SERIALIZERS, PrincipiaMagica.MODID);

    public static final DeferredHolder<EntityDataSerializer<?>, EntityDataSerializer<GolemSpec>> GOLEM_SPEC = ENTITY_DATA_SERIALIZERS.register("golem_spec", () -> EntityDataSerializer.forValueType(GolemSpec.STREAM_CODEC));
}
